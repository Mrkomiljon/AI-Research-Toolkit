#!/usr/bin/env python3
"""Export a human-readable project report (Markdown + DOCX) into <workspace>/exports/ from status, plan and registries.

  python scripts/export_report.py --project workspace/my-project [--docx]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from research_toolkit.evidence_store import EvidenceStore  # noqa: E402
from research_toolkit.exporters import write_docx, write_markdown  # noqa: E402
from research_toolkit.orchestrator import final_report  # noqa: E402
from research_toolkit.progress import compute_status  # noqa: E402
from research_toolkit.project_manager import ProjectManager  # noqa: E402
from research_toolkit.schemas import utcnow  # noqa: E402
from research_toolkit.source_registry import SourceRegistry  # noqa: E402
from research_toolkit.workflow_state import WorkflowState  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", "-p", default=".")
    ap.add_argument("--docx", action="store_true")
    a = ap.parse_args()
    pm = ProjectManager.find(Path(a.project))
    cfg = pm.load_config()
    status = compute_status(pm)
    reg = SourceRegistry(pm.workspace)
    ev = EvidenceStore(pm.workspace).all()
    sections: list[tuple[str, str]] = [
        ("Project", f"- Slug: {cfg.slug}\n- Topic: {cfg.topic}\n- Field: {cfg.field or '-'}\n- Years: {cfg.year_from or '-'}–{cfg.year_to or '-'}\n- Target journal: {cfg.target_journal or '-'}"),
        ("Stage status (derived from artifacts)", "\n".join(f"- {s.skill}: **{s.status}**" + (f" — blockers: {'; '.join(s.blockers)}" if s.blockers else "") for s in status.stages.values())),
        ("Sources", f"- Total: {status.sources_total}; verified metadata: {status.sources_verified}; full text: {status.sources_full_text}\n" + "\n".join(f"- `{s.source_id}` {s.title} ({s.year or 'n.d.'}) DOI {s.doi or 'none'} [{s.access_level.value}]" for s in reg.all()[:50])),
        ("Evidence records", f"- {len(ev)} records; verified by tool/human: {sum(1 for e in ev if e.verification_status.value == 'verified')}"),
        ("Blockers", "\n".join(f"- {b}" for b in status.blockers) or "- none"),
        ("Next actions", "\n".join(f"- {n}" for n in status.next_actions) or "- none"),
    ]
    state = WorkflowState(pm.workspace)
    if state.has_plan():
        rep = final_report(pm, state.load_plan())
        sections.append(("Latest workflow run", f"- Run: {rep['run_id']} status {rep['status']}\n- Files on disk: " + (", ".join(rep['files']) or "none") + "\n- Next: " + ("; ".join(rep['next_steps']) or "none")))
    stamp = utcnow().strftime("%Y%m%d-%H%M")
    out_md = write_markdown(pm.workspace / "exports" / f"project-report-{stamp}.md", f"Research project report — {cfg.title}", sections,
                            front_note="Generated by AI Research Toolkit. Statuses are counts of validated artifacts; interpretation requires the author.")
    print(out_md)
    if a.docx:
        out_docx = write_docx(pm.workspace / "exports" / f"project-report-{stamp}.docx", f"Research project report — {cfg.title}", sections)
        print(out_docx)
    return 0


if __name__ == "__main__":
    sys.exit(main())
