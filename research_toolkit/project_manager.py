"""Research workspace lifecycle: project.yaml, artifact registry, privacy boundary checks."""
from __future__ import annotations

import fnmatch
import hashlib
import json
import re
from datetime import datetime
from pathlib import Path

import yaml

from . import SCHEMA_VERSION
from .paths import ensure_workspace_dirs, rel_to, safe_join
from .schemas import ArtifactRecord, AuthorReviewStatus, ProjectConfig, ValidationStatus, utcnow

SENSITIVE_PATTERNS = [
    re.compile(p, re.IGNORECASE)
    for p in (
        r"\bconfidential\b",
        r"\bdo not distribute\b",
        r"\bpatient[ _-]?id\b",
        r"\bmedical record\b",
        r"\bpassport\b",
        r"\b(?:api[_-]?key|secret[_-]?key|password)\s*[:=]",
        r"\bmaxfiy\b",  # uz: confidential
        r"\bконфиденциально\b",  # ru: confidential
    )
]


class ApprovalRequired(PermissionError):
    """Raised when an action needs explicit human authorization before it may continue."""


class ProjectManager:
    def __init__(self, workspace: Path):
        self.workspace = Path(workspace)
        self.config_path = self.workspace / "project.yaml"
        self.artifacts_path = self.workspace / "progress" / "artifacts.json"

    # ---- creation ------------------------------------------------------
    @classmethod
    def init(cls, root: Path, config: ProjectConfig, overwrite: bool = False) -> ProjectManager:
        ws = Path(root) / config.slug
        pm = cls(ws)
        if pm.config_path.exists() and not overwrite:
            raise FileExistsError(f"workspace already initialised: {pm.config_path}")
        ensure_workspace_dirs(ws)
        pm.save_config(config)
        if not pm.artifacts_path.exists():
            pm._write_artifacts([])
        (ws / "README.md").write_text(
            f"# {config.title}\n\nResearch workspace generated by AI Research Toolkit (schema {SCHEMA_VERSION}).\n"
            "Private PDFs go in papers/PDFs/. Do not commit this folder to a public repository.\n",
            encoding="utf-8",
        )
        return pm

    @classmethod
    def find(cls, path: Path) -> ProjectManager:
        p = Path(path).resolve()
        for cand in (p, *p.parents):
            if (cand / "project.yaml").exists():
                return cls(cand)
        raise FileNotFoundError(f"no project.yaml found at or above {path}")

    # ---- config --------------------------------------------------------
    def load_config(self) -> ProjectConfig:
        return ProjectConfig.model_validate(yaml.safe_load(self.config_path.read_text(encoding="utf-8")))

    def save_config(self, config: ProjectConfig) -> None:
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        self.config_path.write_text(
            yaml.safe_dump(config.model_dump(mode="json"), sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )

    # ---- artifact registry ---------------------------------------------
    def _write_artifacts(self, records: list[ArtifactRecord]) -> None:
        self.artifacts_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"schema_version": SCHEMA_VERSION, "artifacts": [r.model_dump(mode="json") for r in records]}
        self.artifacts_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    def artifacts(self) -> list[ArtifactRecord]:
        if not self.artifacts_path.exists():
            return []
        data = json.loads(self.artifacts_path.read_text(encoding="utf-8"))
        return [ArtifactRecord.model_validate(a) for a in data.get("artifacts", [])]

    def artifacts_by_type(self, artifact_type: str) -> list[ArtifactRecord]:
        return [a for a in self.artifacts() if a.type == artifact_type]

    def resolve(self, relative: str) -> Path:
        return safe_join(self.workspace, relative)

    def register_artifact(
        self,
        path: str | Path,
        *,
        artifact_type: str | None = None,
        skill: str | None = None,
        source_ids: list[str] | None = None,
        run_id: str | None = None,
        step_id: str | None = None,
        validation_status: ValidationStatus = ValidationStatus.PENDING,
        author_review: AuthorReviewStatus = AuthorReviewStatus.NOT_REQUIRED,
        tentative: bool = False,
        notes: str | None = None,
    ) -> ArtifactRecord:
        p = Path(path)
        if p.is_absolute():
            abs_path = p
        else:  # relative paths may be cwd-relative (CLI usage) or workspace-relative (skill usage)
            cwd_candidate = (Path.cwd() / p).resolve()
            try:
                cwd_candidate.relative_to(self.workspace.resolve())
                abs_path = cwd_candidate if cwd_candidate.exists() else safe_join(self.workspace, p)
            except ValueError:
                abs_path = safe_join(self.workspace, p)
        if not abs_path.exists():
            raise FileNotFoundError(f"cannot register missing artifact {abs_path}")
        rel = rel_to(self.workspace, abs_path)
        digest = sha256_of(abs_path)
        record = ArtifactRecord(
            artifact_id="art-" + hashlib.sha1(f"{rel}|{run_id}|{step_id}".encode()).hexdigest()[:10],
            type=artifact_type or abs_path.name,
            path=rel,
            source_ids=source_ids or [],
            workflow_run_id=run_id,
            step_id=step_id,
            skill=skill,
            validation_status=validation_status,
            author_review_status=author_review,
            tentative=tentative,
            sha256=digest,
            notes=notes,
        )
        records = [a for a in self.artifacts() if a.path != rel]
        records.append(record)
        self._write_artifacts(records)
        return record

    def update_artifact(self, rel_path: str, **changes) -> ArtifactRecord:
        records = self.artifacts()
        for i, a in enumerate(records):
            if a.path == rel_path:
                updated = a.model_copy(update=changes)
                records[i] = updated
                self._write_artifacts(records)
                return updated
        raise KeyError(rel_path)

    def user_edited(self, rel_path: str) -> bool:
        """True when the on-disk file no longer matches the hash recorded when the toolkit wrote it."""
        for a in self.artifacts():
            if a.path == rel_path:
                p = self.workspace / rel_path
                return p.exists() and a.sha256 is not None and sha256_of(p) != a.sha256
        return False

    def guard_overwrite(self, rel_path: str, force: bool = False) -> None:
        """Never overwrite a user-edited manuscript automatically (TZ 7.6)."""
        if self.user_edited(rel_path) and not force:
            raise ApprovalRequired(
                f"{rel_path} was edited after the toolkit wrote it; refusing to overwrite without --force"
            )

    # ---- privacy / external transmission ---------------------------------
    def is_restricted(self, rel_path: str) -> bool:
        cfg = self.load_config()
        rel = rel_path.replace("\\", "/")
        return any(fnmatch.fnmatch(rel, g) or fnmatch.fnmatch(rel, g.replace("/**", "/*")) for g in cfg.privacy.restricted_globs)

    def scan_sensitive(self, rel_path: str, max_bytes: int = 200_000) -> list[str]:
        p = self.resolve(rel_path)
        if not p.exists() or p.suffix.lower() in (".pdf", ".docx", ".xlsx", ".png", ".jpg"):
            return []
        text = p.read_bytes()[:max_bytes].decode("utf-8", errors="ignore")
        return [pat.pattern for pat in SENSITIVE_PATTERNS if pat.search(text)]

    def check_external_transmission(self, rel_paths: list[str], *, authorized: bool = False) -> dict:
        """Gate before sending workspace files anywhere outside the machine. Raises ApprovalRequired."""
        cfg = self.load_config()
        findings = {}
        for rel in rel_paths:
            reasons = []
            if self.is_restricted(rel):
                reasons.append("matches restricted_globs in project.yaml")
            hits = self.scan_sensitive(rel)
            if hits:
                reasons.append("sensitive markers: " + ", ".join(hits))
            if reasons:
                findings[rel] = reasons
        if not cfg.privacy.allow_external_apis:
            findings["<project>"] = ["privacy.allow_external_apis is false"]
        if findings and not authorized:
            raise ApprovalRequired("external transmission blocked pending user authorization: " + json.dumps(findings))
        return findings


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _dt(v: datetime | None) -> str | None:
    return v.isoformat() if v else None


